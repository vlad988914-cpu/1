const sortedTypes = (types) => [...types].sort((a, b) => CATALOG_TYPES.indexOf(a) - CATALOG_TYPES.indexOf(b));

function priceSection(types) {
  const list = types && types.length ? types : CATALOG_TYPES;
  return {
    title: "Орієнтовна вартість",
    items: [...list.map((t) => `${t} — ${PRICE_HINTS[t]}`), PRICE_NOTE],
  };
}

function guideSections(types) {
  const sections = [];
  for (const type of types) {
    const g = EQUIPMENT_GUIDE[type];
    if (!g) continue;
    sections.push({ title: `${type}: які бувають`, items: [g.what, ...g.variants] });
    sections.push({ title: `${type}: як обрати`, items: g.choose });
  }
  return sections;
}

function pairSection(types) {
  const items = [];
  const sorted = sortedTypes(types);
  for (let i = 0; i < sorted.length; i++) {
    for (let j = i + 1; j < sorted.length; j++) {
      const text = PAIRS[`${sorted[i]}|${sorted[j]}`];
      if (text) items.push(`${sorted[i]} і ${sorted[j]} — ${text}`);
    }
  }
  return items.length ? { title: "У чому різниця", items } : null;
}

function jobAnswer(job, { withPrice }) {
  const sections = [];
  if (withPrice) sections.push(priceSection(job.equipment.filter((e) => e.need).map((e) => e.type)));
  sections.push({
    title: "Яка техніка потрібна",
    items: job.equipment.map((e) => `${e.type} — ${e.need ? "обов'язково" : "за потреби"}: ${e.why}`),
  });
  if (job.variants && job.variants.length) sections.push({ title: "Який варіант обрати", items: job.variants });
  sections.push({ title: "Як це проходить", items: job.steps, ordered: true });
  sections.push({ title: "Часті помилки", items: job.mistakes });
  const safety = [...(job.safety || []).map((k) => SAFETY[k]), ...(job.safetyNotes || [])];
  if (safety.length) sections.push({ title: "Безпека й дозволи", items: safety });
  sections.push({ title: "Що вказати в заявці", items: job.ask });

  // техніка для підбору з каталогу: обов'язкова + кілька додаткових (макс. 3 типи)
  const needed = job.equipment.filter((e) => e.need).map((e) => e.type);
  const optional = job.equipment.filter((e) => !e.need).map((e) => e.type);
  const types = [...needed, ...optional].slice(0, Math.max(3, needed.length));

  let reply = job.intro;
  if (job.outside) reply += " " + job.outside;
  else reply += " Нижче — яка техніка потрібна, які бувають варіанти, як це проходить і на що звернути увагу. Розгорніть потрібний розділ.";

  return {
    jobId: job.id,
    jobTitle: job.title,
    type: types[0] || null,
    types,
    reply,
    sections,
    options: job.options,
  };
}

/**
 * Відповідь із бази знань. ctx = { types: [...], jobTitle } — що обговорювали перед цим.
 * Повертає null, якщо запит не про техніку/роботи (тоді клієнт покаже загальну відповідь).
 */
export function answerFromKnowledge(text, ctx = {}) {
  const q = norm(text).trim();
  if (!q) return null;

  if (RE_THANKS.test(q)) {
    return { jobId: null, type: null, types: null, reply: "Будь ласка! Якщо потрібна ще якась робота — опишіть її або оберіть вид робіт нижче.", sections: [], options: JOB_PILLS.slice(0, 6) };
  }
  if (RE_GREETING.test(q) && q.length < 40) {
    return { jobId: null, type: null, types: null, reply: "Привіт! Я допоможу підібрати техніку під вашу роботу: підкажу, що потрібно, які бувають варіанти і чим вони відрізняються. Оберіть вид робіт нижче або опишіть своїми словами.", sections: [], options: JOB_PILLS.slice(0, 8) };
  }
  if (RE_HOWITWORKS.test(q)) {
    return {
      jobId: null, type: null, types: null,
      reply: "Клієнт залишає заявку → диспетчер підбирає та розсилає її власникам техніки → один із них підтверджує → ви отримуєте контакт. Щоб здати свою техніку, натисніть «Здаю техніку» й додайте оголошення.",
      sections: [], options: ["Створити заявку", ...JOB_PILLS.slice(0, 4)],
    };
  }

  const mentions = findEquipmentMentions(q);
  const wantsPrice = RE_PRICE.test(q);
  const wantsCompare = RE_COMPARE.test(q);

  // 1. Порівняння / «розкажи про техніку»
  if (wantsCompare && mentions.length > 0) {
    const sections = [];
    const pair = mentions.length > 1 ? pairSection(mentions) : null;
    if (pair) sections.push(pair);
    sections.push(...guideSections(mentions.slice(0, 2)));
    return {
      jobId: null,
      type: mentions[0],
      types: null,
      reply: mentions.length > 1
        ? `Порівняймо: ${mentions.join(" і ")}. Розгорніть розділи нижче — там коротко, коли що підходить. Якщо розкажете задачу, підкажу точніше.`
        : `Ось які бувають варіанти: ${mentions[0]}. Розгорніть розділи нижче. Розкажіть задачу — підкажу, який саме підійде.`,
      sections,
      options: ["Опишу свою задачу", "Скільки це коштує?", "Створити заявку"],
    };
  }

  // 2. Конкретний вид робіт
  const job = findJob(q);
  if (job) return jobAnswer(job, { withPrice: wantsPrice });

  // 3. Ціни (без конкретної роботи): за останньою темою чи за згаданою технікою
  if (wantsPrice) {
    const types = mentions.length ? mentions : ctx.types && ctx.types.length ? ctx.types : null;
    return {
      jobId: null, type: types ? types[0] : null, types: null,
      reply: types ? "Орієнтовні ціни на потрібну техніку — нижче." : "Орієнтовні ціни на всю техніку каталогу — нижче.",
      sections: [priceSection(types)],
      options: ["Створити заявку", "Інша задача"],
    };
  }

  // 4. Згадана техніка без роботи: пояснюємо, що це і які бувають
  if (mentions.length > 0) {
    const sections = [];
    const pair = mentions.length > 1 ? pairSection(mentions) : null;
    if (pair) sections.push(pair);
    sections.push(...guideSections(mentions.slice(0, 2)));
    return {
      jobId: null, type: mentions[0], types: null,
      reply: `Про ${mentions.slice(0, 2).join(" і ")} — коротко нижче. Розкажіть, яку роботу треба виконати, і я скажу, чи підійде вона й що ще знадобиться.`,
      sections,
      options: JOB_PILLS.slice(0, 5),
    };
  }

  return null;
}

