const norm = (s) =>
  String(s || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/ґ/g, "г")
    .replace(/[’ʼ`´]/g, "'");

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// початок слова + корінь (\b не працює з кирилицею)
const hasStem = (text, stem) => new RegExp("(^|[^а-яіїєa-z0-9])" + escapeRe(norm(stem))).test(text);

export function findJob(text) {
  const q = norm(text);
  let best = null;
  let bestScore = 0;
  for (const job of JOBS) {
    let score = 0;
    for (const k of job.keys) if (hasStem(q, k)) score += 1;
    if (score > bestScore) {
      best = job;
      bestScore = score;
    }
  }
  return best;
}

const EQUIP_KEYS = {
  Екскаватор: ["екскават", "экскават", "мініекскав", "міні-екскав", "мини-экскав", "мини экскав"],
  Навантажувач: ["навантажувач", "погрузчик", "бобкат", "bobcat", "міні-навантаж", "телескопічн"],
  Самоскид: ["самоскид", "самосвал", "камаз", "вантажівк"],
  Гідромолот: ["гідромолот", "гидромолот", "молот"],
  Кран: ["кран", "автокран", "маніпулятор", "манипулятор"],
  Бульдозер: ["бульдозер"],
  Каток: ["каток", "катк", "віброплит", "виброплит"],
};

export function findEquipmentMentions(text) {
  const q = norm(text);
  const found = [];
  for (const type of CATALOG_TYPES) {
    let at = -1;
    for (const k of EQUIP_KEYS[type]) {
      const m = new RegExp("(^|[^а-яіїєa-z0-9])" + escapeRe(norm(k))).exec(q);
      if (m && (at === -1 || m.index < at)) at = m.index;
    }
    if (at !== -1) found.push({ type, at });
  }
  return found.sort((a, b) => a.at - b.at).map((x) => x.type);
}

const RE_COMPARE =
  /різниц|відрізня|разниц|отлича|чим .*(кращ|краще)|що краще|що кращ|що вибрат|(який|яка|яке|яку|які|какой|какая|какие)\s+(\S+\s+)?(обрат|вибрат|выбрат)|як вибрат|як обрат|как выбрат|что лучше|порівня|сравни|які бувають|какие бывают|що таке|что такое|для чого|для чего|види |типи |виды |типы |розкажи про|розкажіть про|навіщо/;
const RE_PRICE = /скільки\s+(це\s+|буде\s+)?(кошту|кошт|стоїть)|вартіст|(^|[^а-яіїє])цін[аиуі]|прайс|почому|сколько\s+(это\s+)?сто|стоимост|how much/;
const RE_HOWITWORKS = /як це працю|как это работа|як здат|как сдат|здат[иь] техніку|сдат[ьи] технику|як користуват|як працює сайт|як замовит/;
const RE_GREETING = /^(привіт|вітаю|добрий день|доброго дня|добрий вечір|здравствуй|привет|добрый день|hello|hi)(?![а-яіїєa-z])/;
const RE_THANKS = /^(дякую|дяку|спасибо|thanks|thank you)/;

