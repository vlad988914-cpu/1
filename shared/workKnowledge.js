// Коротка загальна частина + деталі лише по тій роботі й техніці,
// про які йдеться в останніх повідомленнях клієнта — так запит дешевший.
// ============================================================
export function kbPromptText(contextText = "") {
  const lines = [];
  lines.push("ВИДИ РОБІТ ТА ТЕХНІКА З КАТАЛОГУ (джерело фактів; не вигадуй іншого):");
  JOBS.forEach((j, i) => {
    lines.push(`${i + 1}. ${j.title} — техніка: ${j.equipment.map((e) => `${e.type}${e.need ? "*" : ""}`).join(", ")}${j.outside ? " (частина спецтехніки поза каталогом)" : ""}`);
  });
  lines.push("(* — обов'язкова техніка)");

  const job = findJob(contextText);
  if (job) {
    lines.push("");
    lines.push(`ДЕТАЛІ ПО ТЕМІ «${job.title}»:`);
    lines.push("Техніка: " + job.equipment.map((e) => `${e.type} (${e.need ? "обов." : "за потреби"}) — ${e.why}`).join(" "));
    if (job.variants.length) lines.push("Варіанти: " + job.variants.join(" | "));
    lines.push("Як проходить: " + job.steps.map((st, n) => `${n + 1}) ${st}`).join(" "));
    lines.push("Часті помилки: " + job.mistakes.join(" "));
    lines.push("У заявці вказати: " + job.ask.join(" "));
    const extra = [...(job.safety || []).map((k) => SAFETY[k]), ...(job.safetyNotes || [])];
    if (extra.length) lines.push("Безпека: " + extra.join(" "));
    if (job.outside) lines.push("Увага: " + job.outside);
  }

  const mentioned = findEquipmentMentions(contextText).slice(0, 2);
  if (mentioned.length) {
    lines.push("");
    lines.push("РІЗНИЦЯ МІЖ ТЕХНІКОЮ:");
    for (const type of mentioned) {
      const g = EQUIPMENT_GUIDE[type];
      lines.push(`${type}: ${g.what} ${g.variants.join(" | ")} Як обрати: ${g.choose.join(" ")}`);
    }
    const pair = pairSection(mentioned);
    if (pair) lines.push("Порівняння: " + pair.items.join(" "));
  }

  lines.push("");
  lines.push("ОРІЄНТОВНІ ЦІНИ: " + Object.entries(PRICE_HINTS).map(([k, v]) => `${k} ${v}`).join("; ") + ". " + PRICE_NOTE);
  if (!job) lines.push("БЕЗПЕКА (для земляних робіт): " + Object.values(SAFETY).join(" "));
  return lines.join("\n");
}
